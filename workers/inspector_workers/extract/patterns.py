"""Декларативные шаблоны извлечения для параметров Матрицы (метод `regex`).

Один шаблон = «подпись параметра» + значение рядом. Это осознанно консервативный слой: он находит то, что
написано в типовой форме («Площадь застройки — 1 250,5 м²», «Бетон класса В30», «Степень огнестойкости II»),
и не пытается угадывать остальное — для этого есть LLM-слой (extract/llm.py) и NOT_COMPARABLE в движке.
Единицы результата приводятся к единицам Матрицы (normalize.to_matrix_unit).
"""

from __future__ import annotations

import re
from dataclasses import dataclass

# Число: «1 250,5», «1250.5», «0,8». Разделители тысяч — пробел/nbsp.
_NUM = r"(?P<num>\d{1,3}(?:[  ]\d{3})+(?:[.,]\d+)?|\d+(?:[.,]\d+)?)"
_GAP = r"[^\d\n]{0,40}?"  # «: », « — », « составляет », « | » между подписью и числом
_UNIT_LEN = r"(?P<unit>мм|см|м)(?![\w²³])"
_UNIT_AREA = r"(?P<unit>м\s?[²2]|кв\.?\s?м)"
_UNIT_VOL = r"(?P<unit>м\s?[³3]|куб\.?\s?м)"
_UNIT_NONE = r"(?P<unit>)"
# Подпись должна начинаться с границы слова: иначе «бетон» находится внутри «железобетонные».
_WORD_START = r"(?<![\w])"


@dataclass(frozen=True)
class Pattern:
    code: str
    regex: re.Pattern
    kind: str  # number | ordinal | string
    confidence: float = 0.85
    exclude: re.Pattern | None = None  # если строка содержит это — шаблон не применяется (развод M-125/M-128)


def _num(code: str, label: str, unit: str = _UNIT_NONE, conf: float = 0.85, exclude: str | None = None) -> Pattern:
    rx = re.compile(rf"{_WORD_START}(?:{label}){_GAP}{_NUM}\s*(?:{unit})?", re.IGNORECASE)
    return Pattern(code, rx, "number", conf, re.compile(exclude, re.IGNORECASE) if exclude else None)


def _ord(code: str, rx: str, conf: float = 0.85) -> Pattern:
    return Pattern(code, re.compile(_WORD_START + rx, re.IGNORECASE), "ordinal", conf)


def _str(code: str, rx: str, conf: float = 0.8) -> Pattern:
    return Pattern(code, re.compile(_WORD_START + rx, re.IGNORECASE), "string", conf)



